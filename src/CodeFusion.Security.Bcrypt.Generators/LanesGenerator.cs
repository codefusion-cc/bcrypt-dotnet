using System.Globalization;
using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis;

namespace CodeFusion.Security.Generators;

/// <summary>
/// Writes Bcrypt.Lanes.g.cs into the library: bcrypt's hot loop for 1 to 5 hashes interleaved.
/// <para>
/// Each lane's halves are plain locals, so the JIT keeps them in registers (ref parameters made it spill on every
/// round). Each round XORs its P word into the half before F's result arrives, keeping that XOR off the chain the
/// round waits on. Lane k's state starts at k * Lane: S-boxes at 0, P at 1024.
/// </para>
/// <para>
/// The S-box lookups come in two forms, because the best one depends on the instruction set:
/// Offsets (x64 and others): every lookup is st[constant + index]. x64 loads [base + index*4 + constant] in one
/// instruction, so all lanes share one base register. This tied or beat clang -O3 on a Xeon 8581C and gcc -O3 on a
/// Haswell.
/// Base pointers (arm64): arm64 has no load with a scaled index and a constant together, so the offsets form costs
/// four extra instructions per lookup, on the chain each round waits for. With a base pointer per S-box, a lookup is
/// a shift and a load, as clang compiles it. The pointers live in a stack array, so the JIT can't fold them back into
/// one base plus constants. 20 pointers for 5 lanes fit arm64's 31 registers; on x64's 16 they spilled and ran slower.
/// </para>
/// Eight lanes spill registers on x86; five was fastest or tied on the Xeon, the Haswell and an Apple M1.
/// </summary>
[Generator(LanguageNames.CSharp)]
public sealed class LanesGenerator : IIncrementalGenerator
{
    const int Lanes = 5;
    const int Lane = 1048, S = 0, P = 1024;

    /// <inheritdoc/>
    public void Initialize(IncrementalGeneratorInitializationContext context) =>
        context.RegisterPostInitializationOutput(static c => c.AddSource("Bcrypt.Lanes.g.cs", Source()));

    /// <summary>The whole file; line ends are "\n" on every OS, so builds are byte-identical.</summary>
    internal static string Source()
    {
        var sb = new StringBuilder();
        sb.Append(
            "// <auto-generated>\n" +
            "// Written by CodeFusion.Security.Bcrypt.Generators/LanesGenerator.cs when the library compiles.\n" +
            "// </auto-generated>\n" +
            "using System;\n" +
            "using System.Runtime.CompilerServices;\n" +
            "using System.Runtime.Intrinsics.Arm;\n" +
            "\n" +
            "namespace CodeFusion.Security;\n" +
            "\n" +
            "public static unsafe partial class Bcrypt\n" +
            "{\n" +
            "    /// <summary>Hashes interleaved on one thread at most.</summary>\n" +
            $"    public const int MaxLanes = {Lanes};\n" +
            "\n" +
            "    /// <summary>Which form of the loop runs; the generator says why there are two.</summary>\n" +
            "    internal enum LoopForm { Auto, Offsets, BasePointers }\n" +
            "\n" +
            "    /// <summary>For the tests, which run both forms on any machine.</summary>\n" +
            "    [ThreadStatic] internal static LoopForm FormOverride;\n" +
            "\n" +
            "    /// <summary>\n" +
            "    /// <paramref name=\"rounds\"/> rounds of Blowfish_expand0state with the key words, then with the salt words, for\n" +
            "    /// lanes 0 to <paramref name=\"lanes\"/> - 1 together. Lane k's words are wk[18k..] and ws[18k..].\n" +
            "    /// </summary>\n" +
            "    static void ExpandRounds(int lanes, uint* st, uint* wk, uint* ws, long rounds)\n" +
            "    {\n" +
            "        var form = FormOverride;\n" +
            "        if (form == LoopForm.Auto) form = ArmBase.Arm64.IsSupported ? LoopForm.BasePointers : LoopForm.Offsets;\n" +
            "        if (form == LoopForm.BasePointers)\n" +
            "        {\n");
        Switch(sb, "Bases");
        sb.Append(
            "        }\n" +
            "        else\n" +
            "        {\n");
        Switch(sb, "");
        sb.Append("        }\n    }\n");
        for (int n = 1; n <= Lanes; n++) LaneMethods(sb, n, bases: false);
        for (int n = 1; n <= Lanes; n++) LaneMethods(sb, n, bases: true);
        sb.Append("}\n");
        return sb.ToString();
    }

    static void Switch(StringBuilder sb, string name)
    {
        sb.Append("            switch (lanes)\n            {\n");
        for (int n = 1; n <= Lanes; n++) sb.Append($"                case {n}: Loop{name}{n}(st, wk, ws, rounds); break;\n");
        sb.Append("                default: throw new ArgumentOutOfRangeException(nameof(lanes));\n            }\n");
    }

    static string FOffsets(int k, string x)
    {
        int b = k * Lane + S;
        return $"((st[{b} + (nuint)({x} >> 24)] + st[{b + 0x100} + (nuint)(byte)({x} >> 16)]) "
            + $"^ st[{b + 0x200} + (nuint)(byte)({x} >> 8)]) + st[{b + 0x300} + (nuint)(byte){x}]";
    }

    static string FBases(int k, string x) =>
        $"((b{k}0[{x} >> 24] + b{k}1[({x} >> 16) & 0xFF]) ^ b{k}2[({x} >> 8) & 0xFF]) + b{k}3[{x} & 0xFF]";

    static string POffsets(int k, int j) => $"st[{k * Lane + P + j}]";

    static string PBases(int k, int j) => $"b{k}3[{0x100 + j}]"; // P follows the fourth S-box

    /// <summary>One Blowfish encryption of every lane's (l, r), the lanes' rounds interleaved.</summary>
    static void Encipher(StringBuilder sb, int n, string ind, bool bases)
    {
        string F(int k, string x) => bases ? FBases(k, x) : FOffsets(k, x);
        string Pw(int k, int j) => bases ? PBases(k, j) : POffsets(k, j);
        for (int k = 0; k < n; k++) sb.Append($"{ind}l{k} ^= {Pw(k, 0)};\n");
        for (int j = 1; j <= 16; j++)
        {
            string t = j % 2 == 1 ? "r" : "l", s = j % 2 == 1 ? "l" : "r";
            for (int k = 0; k < n; k++) sb.Append($"{ind}{t}{k} ^= {Pw(k, j)}; {t}{k} ^= {F(k, s + k.ToString(CultureInfo.InvariantCulture))};\n");
        }
        for (int k = 0; k < n; k++) sb.Append($"{ind}{{ uint t = r{k} ^ {Pw(k, 17)}; r{k} = l{k}; l{k} = t; }}\n");
    }

    static void LaneMethods(StringBuilder sb, int n, bool bases)
    {
        const string ind = "            ";
        string name = bases ? "Bases" : "";
        string zero = string.Join(", ", Enumerable.Range(0, n).Select(k => $"l{k} = 0, r{k} = 0"));
        string param = bases ? ", uint** b" : "", arg = bases ? ", b" : "";
        string summary = bases ? "with a base pointer per S-box (arm64)" : "with constant offsets from st (x64)";

        sb.Append($"\n    static void Loop{name}{n}(uint* st, uint* wk, uint* ws, long rounds)\n    {{\n");
        if (bases)
        {
            sb.Append($"        uint** b = stackalloc uint*[{4 * n}];\n");
            sb.Append($"        for (int k = 0; k < {n}; k++)\n");
            sb.Append("            for (int m = 0; m < 4; m++) b[4 * k + m] = st + k * Lane + m * 256;\n");
        }
        sb.Append("        for (long n = rounds; n > 0; n--)\n        {\n");
        sb.Append($"            Expand0State{name}{n}(st, wk{arg});\n");
        sb.Append($"            Expand0State{name}{n}(st, ws{arg});\n");
        sb.Append("        }\n    }\n\n");

        sb.Append($"    /// <summary>Blowfish_expand0state for {n} lane{(n > 1 ? "s" : "")} {summary}: lane k XORs w[18k..18k+17] into its P, then re-derives P and S.</summary>\n");
        sb.Append("    [MethodImpl(MethodImplOptions.AggressiveOptimization)]\n");
        sb.Append($"    static void Expand0State{name}{n}(uint* st, uint* w{param})\n    {{\n");
        if (bases)
            for (int k = 0; k < n; k++)
                for (int m = 0; m < 4; m++)
                    sb.Append($"        uint* b{k}{m} = b[{4 * k + m}];\n");

        sb.Append("        for (nuint i = 0; i < 18; i++)\n        {\n");
        for (int k = 0; k < n; k++) sb.Append($"{ind}st[{k * Lane + P} + i] ^= w[{k * 18} + i];\n");
        sb.Append("        }\n");
        sb.Append($"        uint {zero};\n");

        sb.Append("        for (nuint i = 0; i < 18; i += 2)\n        {\n");
        Encipher(sb, n, ind, bases);
        for (int k = 0; k < n; k++) sb.Append($"{ind}st[{k * Lane + P} + i] = l{k}; st[{k * Lane + P} + i + 1] = r{k};\n");
        sb.Append("        }\n");

        sb.Append("        for (nuint i = 0; i < 1024; i += 2)\n        {\n");
        Encipher(sb, n, ind, bases);
        for (int k = 0; k < n; k++) sb.Append($"{ind}st[{k * Lane + S} + i] = l{k}; st[{k * Lane + S} + i + 1] = r{k};\n");
        sb.Append("        }\n    }\n");
    }
}
